// language.js — language support for PromptForge (v3 feature D)
//
// Provides the supported-language registry, BCP-47 normalisation, and offline
// language detection (en vs zh-HK vs zh-CN). Detection is intentionally
// offline and dependency-free: it must run in every context (app tab,
// service worker, bundled content script) with no network.
//
// zh-HK vs zh-CN discrimination is a Traditional-vs-Simplified character
// heuristic. It is accurate on typical prompt text but is a heuristic —
// callers treat low confidence as "ask the user" (locked product decision).

export const SUPPORTED_LANGUAGES = Object.freeze([
  Object.freeze({ code: 'en', label: 'English', short: 'EN' }),
  Object.freeze({ code: 'zh-HK', label: '中文（繁體）', short: '繁' }),
  Object.freeze({ code: 'zh-CN', label: '中文（简体）', short: '简' }),
]);

export const DEFAULT_PROMPT_LANGUAGES = Object.freeze(['en', 'zh-HK', 'zh-CN']);

// English names used when instructing the AI model (model-facing, not UI).
export const LANGUAGE_NAMES = Object.freeze({
  'en': 'English',
  'zh-HK': 'Traditional Chinese',
  'zh-CN': 'Simplified Chinese',
});

/**
 * Build the language directive appended to AI system prompts.
 * @param {string|null} code - BCP-47 code; null/unknown → no directive (the
 *   model naturally mirrors the prompt's own language).
 * @returns {string}
 */
export function languageDirective(code) {
  const normalized = normalizeLangCode(code);
  const name = LANGUAGE_NAMES[normalized];
  if (!name) return '';
  return `\n\nLanguage requirement:\n- Write your output in ${name}.\n- Do NOT translate code blocks, #variables#, URLs, or proper nouns.\n- Keep the same register and tone as the original prompt.`;
}

/**
 * Normalise a language code to BCP-47 casing: "zh-hk" → "zh-HK", "EN" → "en".
 * Returns null for anything that isn't a plausible code.
 * @param {string} raw
 * @returns {string|null}
 */
export function normalizeLangCode(raw) {
  if (typeof raw !== 'string') return null;
  const parts = raw.trim().split(/[-_]/).filter(Boolean);
  if (parts.length === 0) return null;
  const primary = parts[0].toLowerCase();
  if (!/^[a-z]{2,3}$/.test(primary)) return null;
  if (parts.length === 1) return primary;
  const region = parts[1].toUpperCase();
  if (!/^[A-Z]{2}$/.test(region)) return primary;
  return `${primary}-${region}`;
}

/** Look up display metadata for a code. Unknown codes get a derived label. */
export function languageMeta(code) {
  const normalized = normalizeLangCode(code);
  return SUPPORTED_LANGUAGES.find(l => l.code === normalized)
    || { code: normalized || code, label: normalized || String(code), short: (normalized || String(code)).toUpperCase() };
}

