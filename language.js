const SIMP_ONLY = new Set(SIMP_TRAD_PAIRS.map(p => p[0]));
const TRAD_ONLY = new Set(SIMP_TRAD_PAIRS.map(p => p[1]));

// CJK Unified Ideographs (+ Ext-A, compat) — roughly "is this a Han character".
const CJK_RE = /[㐀-鿿豈-﫿]/g;
const NONSPACE_RE = /\S/g;

/**
 * Detect the language of a prompt's text.
 * @param {string} text
 * @returns {{ code: string|null, confidence: number }}
 *   code: 'en' | 'zh-HK' | 'zh-CN' | null (undeterminable)
 *   confidence: 0..1 — callers should treat < 0.75 as "ask the user".
 */
export function detectLanguage(text) {
  const src = typeof text === 'string' ? text : '';
  const nonSpace = src.match(NONSPACE_RE);
  if (!nonSpace || nonSpace.length === 0) return { code: null, confidence: 0 };

  const cjk = src.match(CJK_RE);
  const cjkCount = cjk ? cjk.length : 0;
  const cjkRatio = cjkCount / nonSpace.length;

  // Latin-dominant text → English (the only supported Latin locale). Require
  // at least one Latin letter — pure digits/symbols have no detectable language.
  if (cjkRatio < 0.15) {
    const hasLatin = /[A-Za-z]/.test(src);
    return hasLatin ? { code: 'en', confidence: 0.9 } : { code: null, confidence: 0 };
  }

  // CJK-dominant text → discriminate Traditional (zh-HK) vs Simplified (zh-CN)
  // by counting characters that exist in only one form.
  let trad = 0;
  let simp = 0;
  for (const ch of src) {
    if (TRAD_ONLY.has(ch)) trad++;
    else if (SIMP_ONLY.has(ch)) simp++;
  }
  const discriminators = trad + simp;
  // No discriminating characters (all shared forms) — genuinely undeterminable.
  if (discriminators === 0) return { code: null, confidence: 0 };

  const code = trad >= simp ? 'zh-HK' : 'zh-CN';
  const dominance = Math.max(trad, simp) / discriminators;
  // High confidence: several discriminators and a clear majority for one form.
  // Mixed Traditional+Simplified text scores low → callers ask the user.
  const confidence = (discriminators >= 3 && dominance >= 0.75) ? 0.9
    : (dominance >= 0.6 ? 0.5 : 0.2);
  return { code, confidence };
}
